            endereco.Cep = cols.Length > 4 && cols[4] != "NULL" ? cols[4] : string.Empty;
            endereco.Logradouro = cols.Length > 5 && cols[5] != "NULL" ? cols[5] : string.Empty;
            endereco.Complemento = cols.Length > 6 && cols[6] != "NULL" ? cols[6] : null;
            endereco.Numero = cols.Length > 7 && cols[7] != "NULL" ? cols[7] : null;

            if (cols.Length > 8 && decimal.TryParse(cols[8].Replace(',', '.'), System.Globalization.NumberStyles.Any, System.Globalization.CultureInfo.InvariantCulture, out decimal lat))
            {
                endereco.Latitude = lat;
            }
            if (cols.Length > 9 && decimal.TryParse(cols[9].Replace(',', '.'), System.Globalization.NumberStyles.Any, System.Globalization.CultureInfo.InvariantCulture, out decimal lon))
            {
                endereco.Longitude = lon;
            }
        }
        context.SaveChanges();

        try
        {
            context.Database.ExecuteSqlRaw("SELECT setval(pg_get_serial_sequence('\"enderecos\"', 'id'), coalesce(max(\"id\"), 1)) FROM \"enderecos\";");
        }
        catch { }
    }

    private static void SeedEmpreendimentosEnderecosFromDump(ApplicationDbContext context)
    {
        var dumpPath = @"C:\Projects\novuu\api\empreendimentos_enderecos_dump_utf8.txt";
        if (!System.IO.File.Exists(dumpPath)) return;

        var lines = System.IO.File.ReadAllLines(dumpPath);
        if (lines.Length <= 1) return;

        for (int i = 1; i < lines.Length; i++)
        {
            var line = lines[i];
            if (string.IsNullOrWhiteSpace(line)) continue;

            var cols = line.Split('\t');
            if (cols.Length < 2) continue;
            if (!int.TryParse(cols[0], out int empId)) continue;
            if (!int.TryParse(cols[1], out int endId)) continue;

            var emp = context.Empreendimentos.FirstOrDefault(e => e.Id == empId);
            if (emp != null)
            {
                emp.EnderecoId = endId;
            }
        }
        context.SaveChanges();
    }
