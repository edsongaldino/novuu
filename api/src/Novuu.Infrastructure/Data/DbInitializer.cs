    private static void SeedConstrutorasFromDump(ApplicationDbContext context)
    {
        var dumpPath = @"C:\Projects\novuu\api\construtoras_dump.txt";
        if (!System.IO.File.Exists(dumpPath)) return;

        var lines = System.IO.File.ReadAllLines(dumpPath);
        if (lines.Length <= 1) return;

        for (int i = 1; i < lines.Length; i++)
        {
            var line = lines[i];
            if (string.IsNullOrWhiteSpace(line)) continue;

            var cols = line.Split('\t');
            if (cols.Length < 2) continue;

            if (!int.TryParse(cols[0], out int id)) continue;

            var construtora = context.Construtoras.FirstOrDefault(c => c.Id == id);
            bool isNew = false;
            if (construtora == null)
            {
                construtora = new Construtora { Id = id };
                isNew = true;
            }

            construtora.Nome = cols.Length > 1 && cols[1] != "NULL" ? cols[1] : string.Empty;
            construtora.NomeAbreviado = cols.Length > 2 && cols[2] != "NULL" ? cols[2] : null;
            construtora.RazaoSocial = cols.Length > 3 && cols[3] != "NULL" ? cols[3] : null;
            construtora.Cnpj = cols.Length > 4 && cols[4] != "NULL" ? cols[4] : null;
            var rawLogo = cols.Length > 5 && cols[5] != "NULL" ? cols[5] : null;
            if (!string.IsNullOrWhiteSpace(rawLogo) && !rawLogo.StartsWith("http"))
            {
                var cleanLogo = rawLogo.TrimStart('/', '\\').Replace('/', System.IO.Path.DirectorySeparatorChar);
                var diskPath = System.IO.Path.Combine(@"C:\laragon\www\lancamentos\public", cleanLogo);
                if (!System.IO.File.Exists(diskPath))
                {
                    rawLogo = null;
                }
            }
            construtora.Logo = rawLogo;
            construtora.Observacoes = cols.Length > 6 && cols[6] != "NULL" ? cols[6] : null;
            construtora.TempoMercado = cols.Length > 7 && cols[7] != "NULL" ? cols[7] : null;
            if (cols.Length > 8 && int.TryParse(cols[8], out int ano)) construtora.AnoFundacao = ano;
            if (cols.Length > 9 && int.TryParse(cols[9], out int mes)) construtora.MesFundacao = mes;
            construtora.Email = cols.Length > 10 && cols[10] != "NULL" ? cols[10] : null;
            construtora.Telefone = cols.Length > 11 && cols[11] != "NULL" ? cols[11] : null;
            construtora.CelularAtendimento = cols.Length > 12 && cols[12] != "NULL" ? cols[12] : null;
            construtora.Whatsapp = cols.Length > 13 && cols[13] != "NULL" ? cols[13] : null;
            construtora.UrlHotsite = cols.Length > 14 && cols[14] != "NULL" ? cols[14] : null;
            construtora.Facebook = cols.Length > 15 && cols[15] != "NULL" ? cols[15] : null;
            construtora.Instagram = cols.Length > 16 && cols[16] != "NULL" ? cols[16] : null;
            construtora.Twitter = cols.Length > 17 && cols[17] != "NULL" ? cols[17] : null;
            construtora.Youtube = cols.Length > 18 && cols[18] != "NULL" ? cols[18] : null;
            construtora.Status = cols.Length > 19 && cols[19] != "NULL" ? cols[19] : "Liberada";
            construtora.AcessoDomus = cols.Length > 20 && cols[20] == "Sim";

            if (isNew)
            {
                context.Construtoras.Add(construtora);
            }
        }

        context.SaveChanges();

        try
        {
            context.Database.ExecuteSqlRaw("SELECT setval(pg_get_serial_sequence('\"Construtoras\"', 'Id'), coalesce(max(\"Id\"), 1)) FROM \"Construtoras\";");
